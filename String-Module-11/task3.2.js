// Task 3.2 — Combine Strings
// Use .concat() to join "Hello" and "World" into "Hello World".
let firstName = 'Hello';
let lastName = 'World';
console.log(firstName, ' '.concat (lastName));

// Usetemplate literals to do the same thing. Compare all three approaches.
console.log(`${firstName}  ${lastName}`);

// Use + to do the same thing. Compare all three approaches.
console.log(firstName,' ' +lastName );

